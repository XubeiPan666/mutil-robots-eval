import pickle, os
import numpy as np
import pdb
import zarr
import shutil
import argparse


def main():
    parser = argparse.ArgumentParser(description='Convert dual-camera PKL data to Zarr format.')
    parser.add_argument('--task_name', type=str, required=True,
                        help='The name of the task (e.g., pick_car_clean)')
    parser.add_argument('--agent_id', type=int, required=True,
                        help='The id of the agent (e.g., 0)')
    parser.add_argument('--load_num', type=int, required=True,
                        help='Number of episodes to process (e.g., 1)')
    args = parser.parse_args()

    task_name = args.task_name
    agent_id = args.agent_id
    num = args.load_num
    
    # Input: PKL directory with dual camera data
    load_dir = f'data/pkl_data/{task_name}_dual_cam_Agent{agent_id}'
    
    total_count = 0
    # Output: Zarr with dual camera data
    save_dir = f'data/zarr_data/{task_name}_dual_cam_Agent{agent_id}_{num}.zarr'

    if os.path.exists(save_dir):
        print(f"Removing existing zarr directory: {save_dir}")
        shutil.rmtree(save_dir)

    current_ep = 0

    zarr_root = zarr.group(save_dir)
    zarr_data = zarr_root.create_group('data')
    zarr_meta = zarr_root.create_group('meta')

    # Arrays for dual camera: img1 (wrist) and img2 (global head)
    img1_arrays, img2_arrays = [], []
    episode_ends_arrays, action_arrays, state_arrays = [], [], []
    
    print(f"Converting dual camera PKL to Zarr...")
    print(f"  Input: {load_dir}")
    print(f"  Output: {save_dir}")
    
    while os.path.isdir(load_dir + f'/episode{current_ep}') and current_ep < num:
        print(f'Processing episode: {current_ep + 1} / {num}', end='\r')
        file_num = 0
        
        while os.path.exists(load_dir + f'/episode{current_ep}' + f'/{file_num}.pkl'):
            with open(load_dir + f'/episode{current_ep}' + f'/{file_num}.pkl', 'rb') as file:
                data = pickle.load(file)
            
            # Read dual camera images
            # img1 = wrist_camera_agent{agent_id}
            # img2 = head_camera_global
            if 'img1' not in data['observation'] or 'img2' not in data['observation']:
                raise KeyError(
                    f"Expected 'img1' and 'img2' in observation, but got keys: {list(data['observation'].keys())}\n"
                    f"Make sure you're using PKL data generated by parse_h5_to_pkl_dual_cam.py"
                )
            
            img1 = data['observation']['img1']['rgb']  # wrist camera
            img2 = data['observation']['img2']['rgb']  # global head camera
            action = data['endpose']
            joint_action = data['joint_action']
            
            # Validate dimensions
            if action is not None:
                action = np.array(action)
                if action.ndim == 0:
                    action = action.reshape(1)
                assert action.shape[-1] == 8, f"endpose 应该是 8 维，但得到 {action.shape[-1]} 维"
            if joint_action is not None:
                joint_action = np.array(joint_action)
                if joint_action.ndim == 0:
                    joint_action = joint_action.reshape(1)
                assert joint_action.shape[-1] == 9, f"joint_action (qpos) 应该是 9 维，但得到 {joint_action.shape[-1]} 维"

            img1_arrays.append(img1)
            img2_arrays.append(img2)
            action_arrays.append(action)
            state_arrays.append(joint_action)

            file_num += 1
            total_count += 1
            
        current_ep += 1
        episode_ends_arrays.append(total_count)

    print()
    print(f"Total steps collected: {total_count}")
    
    episode_ends_arrays = np.array(episode_ends_arrays)
    action_arrays = np.array(action_arrays)
    state_arrays = np.array(state_arrays)
    img1_arrays = np.array(img1_arrays)
    img2_arrays = np.array(img2_arrays)
    
    # Final dimension validation
    print(f"action_arrays shape: {action_arrays.shape}, 期望最后一维为 8")
    print(f"state_arrays shape: {state_arrays.shape}, 期望最后一维为 9")
    print(f"img1_arrays shape: {img1_arrays.shape}, 期望 (N, H, W, 3)")
    print(f"img2_arrays shape: {img2_arrays.shape}, 期望 (N, H, W, 3)")
    
    assert action_arrays.shape[-1] == 8, f"action 应该是 8 维，但得到 {action_arrays.shape[-1]} 维"
    assert state_arrays.shape[-1] == 9, f"state 应该是 9 维，但得到 {state_arrays.shape[-1]} 维"

    # Convert images from NHWC to NCHW format
    img1_arrays = np.moveaxis(img1_arrays, -1, 1)  # NHWC -> NCHW
    img2_arrays = np.moveaxis(img2_arrays, -1, 1)  # NHWC -> NCHW
    
    print(f"After transpose:")
    print(f"img1_arrays shape: {img1_arrays.shape}, 期望 (N, 3, H, W)")
    print(f"img2_arrays shape: {img2_arrays.shape}, 期望 (N, 3, H, W)")

    # Create zarr datasets with compression
    compressor = zarr.Blosc(cname='zstd', clevel=3, shuffle=1)
    action_chunk_size = (100, action_arrays.shape[1])
    state_chunk_size = (100, state_arrays.shape[1])
    img_chunk_size = (100, *img1_arrays.shape[1:])
    
    # Save with keys matching pairwise format: img1, img2, state, action
    zarr_data.create_dataset('img1', data=img1_arrays, chunks=img_chunk_size, 
                             overwrite=True, compressor=compressor)
    zarr_data.create_dataset('img2', data=img2_arrays, chunks=img_chunk_size, 
                             overwrite=True, compressor=compressor)
    zarr_data.create_dataset('state', data=state_arrays, chunks=state_chunk_size, 
                             dtype='float32', overwrite=True, compressor=compressor)
    zarr_data.create_dataset('action', data=action_arrays, chunks=action_chunk_size, 
                             dtype='float32', overwrite=True, compressor=compressor)
    zarr_meta.create_dataset('episode_ends', data=episode_ends_arrays, dtype='int64', 
                             overwrite=True, compressor=compressor)
    
    print(f"\n✓ Dual camera Zarr conversion complete!")
    print(f"  Saved to: {save_dir}")
    print(f"  Keys: img1 (wrist), img2 (global head), state, action")
    print(f"  Episodes: {len(episode_ends_arrays)}, Total steps: {total_count}")

if __name__ == '__main__':
    main()
